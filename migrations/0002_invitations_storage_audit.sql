-- 0002: admin invitations, durable file storage, audit log, persistent presence, session revocation.

-- Bumped on password change/reset and deactivation; a session cookie carrying an older value is rejected.
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;

-- Single-use, expiring admin invitations. Only the SHA-256 of the token is stored.
CREATE TABLE IF NOT EXISTS admin_invitations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email CITEXT NOT NULL,
    full_name TEXT,
    token_hash TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED')),
    invited_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    expires_at TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (cc_now()),
    last_sent_at TEXT,
    send_count INTEGER NOT NULL DEFAULT 0,
    delivery_status TEXT NOT NULL DEFAULT 'NOT_SENT' CHECK (delivery_status IN ('NOT_SENT', 'SENT', 'FAILED', 'NOT_CONFIGURED')),
    accepted_at TEXT,
    accepted_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL
);
-- At most one live invitation per address (duplicate-invitation guard that survives races).
CREATE UNIQUE INDEX IF NOT EXISTS uq_admin_invitations_pending_email ON admin_invitations(email) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_admin_invitations_status ON admin_invitations(status, expires_at);

-- Uploads live in PostgreSQL: Render Free's filesystem is wiped on every restart/deploy.
-- path is the same relative key the app always used (chat/<uuid>.<ext>, profile/<role>/<uuid>.<ext>).
CREATE TABLE IF NOT EXISTS file_blobs (
    path TEXT PRIMARY KEY,
    content BYTEA NOT NULL,
    content_type TEXT NOT NULL,
    size_bytes INTEGER NOT NULL,
    created_at TEXT NOT NULL DEFAULT (cc_now())
);

CREATE TABLE IF NOT EXISTS audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    actor_email TEXT,
    action TEXT NOT NULL,
    target TEXT,
    detail TEXT,
    ip TEXT,
    created_at TEXT NOT NULL DEFAULT (cc_now())
);
CREATE INDEX IF NOT EXISTS idx_audit_log_created ON audit_log(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_log_actor ON audit_log(actor_user_id, created_at);

-- Presence survives restarts (it used to be an in-process dict).
CREATE TABLE IF NOT EXISTS presence (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    last_seen_epoch BIGINT NOT NULL
);

-- Paging/ordering support for the lists that used to be unbounded.
CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON notifications(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_chat_id ON messages(chat_id, id);
